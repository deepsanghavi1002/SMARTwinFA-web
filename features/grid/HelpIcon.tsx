export function helpIconFor(title: string | undefined): HelpIconName {
  const name = (title ?? "").toUpperCase();
  if (name.includes("ACCOUNT")) return "users";
  if (name.includes("PRODUCT")) return "package";
  if (name.includes("FIND")) return "file-text";
  if (name.includes("ADDRESS")) return "map-pin";
  return "circle-help";
}

export function HelpIcon({ name, size = 18 }: { name: HelpIconName; size?: number }) {
  return (
    <svg className="mp-help-icon" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      {PATHS[name]}
    </svg>
  );
}
